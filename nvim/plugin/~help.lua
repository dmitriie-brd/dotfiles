-- Learning helpers. All keys under <leader>h.
--   :Cheatsheet  (<leader>hc)  curated cheatsheet: doc/cheatsheet.md
--   :LearnPlan   (<leader>hl)  learning plan with checkboxes: doc/learning-plan.md (edit + :w)
--                Both open as buffers in the current window (<S-h>/<S-l> reach them);
--                q closes the buffer (asks to save if modified).
--   :Keymaps     (<leader>hk)  generated table of every keymap in this config (file:line)
--   :Drill[!]    (<leader>hd)  (re)create the practice sandbox ~/nvim-drill (copies of zon
--                              files in a git repo). ! = reset without asking.
local m = require('helpers.map')
local doc_dir = vim.fn.stdpath('config') .. '/doc/'

-- Open a doc as a normal buffer in the current window (it joins the buffer line).
local function open_doc(name)
    vim.cmd.edit(vim.fn.fnameescape(doc_dir .. name))
    vim.wo[0][0].spell = false
    vim.wo[0][0].wrap = false
    vim.wo[0][0].conceallevel = 0
    vim.keymap.set(
        'n',
        'q',
        function() Snacks.bufdelete() end,
        { buffer = 0, desc = 'Close this doc buffer' }
    )
end

----------------------------------------
-- Generated keymap table
----------------------------------------
local function generate()
    local groups, order = {}, {}
    for _, k in ipairs(m.registry) do
        local g = k.where:match('^([^:]+)') or '?'
        if not groups[g] then
            groups[g] = {}
            table.insert(order, g)
        end
        table.insert(groups[g], k)
    end
    local lines = {
        '# Neovim keymaps (generated by :Keymaps)',
        '',
        '<leader> = Space. Buffer-local maps appear after the first file of that type is opened.',
        'Curated version: :Cheatsheet',
        '',
    }
    for _, g in ipairs(order) do
        vim.list_extend(
            lines,
            { '## ' .. g, '', '| Mode | Keys | Action | Defined at |', '|---|---|---|---|' }
        )
        for _, k in ipairs(groups[g]) do
            local lhs = k.lhs:gsub('|', '\\|')
            table.insert(
                lines,
                ('| %s | `%s` | %s%s | %s |'):format(
                    k.mode,
                    lhs,
                    k.desc,
                    k.buffer and ' (buffer)' or '',
                    k.where
                )
            )
        end
        table.insert(lines, '')
    end
    return lines
end

local function show_keymaps()
    vim.cmd('tabnew')
    local buf = vim.api.nvim_get_current_buf()
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, generate())
    vim.bo[buf].buftype = 'nofile'
    vim.bo[buf].bufhidden = 'wipe'
    vim.bo[buf].filetype = 'markdown'
    vim.bo[buf].modifiable = false
    vim.wo[0][0].spell = false
    pcall(vim.api.nvim_buf_set_name, buf, 'keymaps://generated')
    vim.keymap.set('n', 'q', '<cmd>tabclose<CR>', { buffer = buf })
end

----------------------------------------
-- Practice sandbox
----------------------------------------
local DRILL = vim.fn.expand('~/nvim-drill')
local DRILL_FILES = {
    { 'pkg/util/date.js', 'date.js' },
    { 'pkg/util/array.js', 'array.js' },
    { 'pkg/util/string.js', 'string.js' },
    { 'pkg/util/url.js', 'url.js' },
    { 'pkg/util/escape.js', 'escape.js' },
    { 'pkg/util/tests/date.test.js', 'tests/date.test.js' },
    { 'pkg/www/locale/pub/lang_select_react.js', 'react/lang_select_react.js' },
}

local function drill(bang)
    local zon = require('zon.root').zon_root() or vim.fn.expand('~/zon1')
    if vim.fn.isdirectory(zon .. '/pkg') == 0 then
        return vim.notify('zon checkout not found (open a zon file first)', vim.log.levels.ERROR)
    end
    if vim.fn.isdirectory(DRILL) == 1 and not bang then
        local ok =
            vim.fn.confirm('Reset ' .. DRILL .. '? All changes in it are lost.', '&Yes\n&No', 2)
        if ok ~= 1 then return end
    end
    -- Drop buffers of the old sandbox.
    for _, b in ipairs(vim.api.nvim_list_bufs()) do
        if vim.startswith(vim.api.nvim_buf_get_name(b), DRILL .. '/') then
            pcall(vim.api.nvim_buf_delete, b, { force = true })
        end
    end
    vim.fn.delete(DRILL, 'rf')
    for _, f in ipairs(DRILL_FILES) do
        local dst = DRILL .. '/' .. f[2]
        vim.fn.mkdir(vim.fs.dirname(dst), 'p')
        vim.uv.fs_copyfile(zon .. '/' .. f[1], dst)
    end
    local function git(args)
        return vim.system(vim.list_extend({ 'git', '-C', DRILL }, args), { text = true }):wait()
    end
    git({ 'init', '-q' })
    git({ 'add', '-A' })
    git({ 'commit', '-q', '-m', 'drill start' })
    vim.cmd('tabnew')
    vim.cmd.tcd(DRILL)
    vim.cmd.edit('date.js')
    vim.notify('Drill sandbox ready: ' .. DRILL .. ' (git repo, reset with :Drill)')
end

----------------------------------------
-- Commands and keys
----------------------------------------
local cmd = vim.api.nvim_create_user_command
cmd(
    'Cheatsheet',
    function() open_doc('cheatsheet.md') end,
    { desc = 'Open the curated cheatsheet' }
)
cmd('LearnPlan', function() open_doc('learning-plan.md') end, { desc = 'Open the learning plan' })
cmd('Keymaps', show_keymaps, { desc = 'Generated table of all config keymaps' })
cmd(
    'Drill',
    function(o) drill(o.bang) end,
    { bang = true, desc = 'Create / reset the practice sandbox ~/nvim-drill' }
)

m.nmap('<leader>hc', '<cmd>Cheatsheet<CR>', 'Cheatsheet')
m.nmap('<leader>hl', '<cmd>LearnPlan<CR>', 'Learning plan')
m.nmap('<leader>hk', '<cmd>Keymaps<CR>', 'All config keymaps (generated)')
m.nmap('<leader>hd', '<cmd>Drill<CR>', 'Practice sandbox (~/nvim-drill)')
m.nmap('<leader>ht', '<cmd>Tutor<CR>', 'Vim tutor (:Tutor)')
